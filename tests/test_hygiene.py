from __future__ import annotations

import subprocess
import unittest
from unittest.mock import patch

from support import Sandbox

from dv import hygiene


class HygieneTests(unittest.TestCase):
    def box(self, **kwargs):
        box = Sandbox(**kwargs)
        self.addCleanup(box.close)
        return box

    def findings(self, box, name):
        return [r for r in hygiene.run(box.item)["checks"] if r["check"] == name]

    def test_clean_change(self):
        output = hygiene.run(self.box().item)
        self.assertTrue(output["ok"], output)
        self.assertEqual(output["stats"]["src_lines"], 2)

    def test_comment_syntax(self):
        for path, text in [
            ("a.ts", "// note"),
            ("a.tsx", "{/* note */}"),
            ("a.py", "x = 1 # note"),
            ("a.ts", "let x = 1; // note"),
            ("a.html", "<!-- note -->"),
        ]:
            self.assertTrue(hygiene.is_comment(path, text), (path, text))
        for path, text in [
            ("a.ts", "#private = 1"),
            ("a.sh", "#!/bin/sh"),
            ("a.ts", 'const url = "https://example.invalid";'),
            ("a.ts", "*/"),
            ("a.ts", "const x = a * b;"),
        ]:
            self.assertFalse(hygiene.is_comment(path, text), (path, text))

    def test_added_source_comment_fails_and_reason_waives(self):
        box = self.box(new={"src/value.ts": "// returns a value\nfixed\n"})
        self.assertEqual(self.findings(box, "source comment")[0]["outcome"], "fail")
        box.update(exceptions={"comment_justification": "Records the non-obvious external format"})
        output = hygiene.run(box.item)
        self.assertTrue(output["ok"], output)
        self.assertIn("comment_justification", str(output["checks"]))

    def test_existing_comment_edit_warns(self):
        box = self.box(
            old={"src/value.ts": "// broken value\nbroken\n"},
            new={"src/value.ts": "// fixed value\nfixed\n"},
        )
        self.assertFalse(self.findings(box, "source comment"))
        self.assertEqual(self.findings(box, "comment edit")[0]["outcome"], "warn")

    def test_replacement_does_not_exempt_extra_comments(self):
        box = self.box(
            old={"src/value.ts": "// one\nbroken\n"},
            new={"src/value.ts": "// two\n// extra\nfixed\n"},
        )
        self.assertEqual(len(self.findings(box, "source comment")), 1)

    def test_directives_warn(self):
        box = self.box(new={"src/value.ts": "// @ts-ignore\nfixed\n"})
        self.assertEqual(self.findings(box, "directive")[0]["outcome"], "warn")
        self.assertFalse(self.findings(box, "source comment"))

    def test_test_comments_warn_only_after_three(self):
        box = self.box(new={"tests/notes.py": "# a\n# b\n# c\n# d\n"})
        self.assertEqual(self.findings(box, "test comments")[0]["outcome"], "warn")
        self.assertFalse(self.findings(box, "source comment"))

    def test_hard_tells_and_technical_product_names(self):
        for text in [
            "Generated with Claude Code",
            "Generated by Codex",
            "As an AI, I made this change",
            "Co-Authored-By: Copilot <bot@example.invalid>",
            "<placeholder>",
            "\U0001f916",
        ]:
            self.assertTrue(hygiene.prose_findings("text", text)[0], text)
        for text in [
            "Supports the Anthropic and OpenAI formats and the Claude Code provider.",
            "A language model can produce this response shape.",
            "Return an empty list.",
        ]:
            self.assertFalse(hygiene.prose_findings("text", text)[0], text)

    def test_authorship_checked_in_comments_commits_and_description(self):
        box = self.box(new={"tests/example.py": "# Generated by Codex\n"})
        self.assertTrue(self.findings(box, "authorship"))
        box.write("tests/example.py", "value = 1\n")
        box.commit("Generated with Claude Code")
        self.assertTrue(self.findings(box, "authorship"))
        box.write(".dv/description.txt", "Generated by Copilot")
        box.update(description_file=".dv/description.txt")
        self.assertGreaterEqual(len(self.findings(box, "authorship")), 2)

    def test_exact_line_exemptions_stay_visible(self):
        line = "Generated with Claude Code"
        self.assertFalse(hygiene.prose_findings("text", line, [line])[0])
        self.assertTrue(hygiene.prose_findings("text", " " + line, [line])[0])
        box = self.box()
        box.write(".dv/description.txt", line)
        box.update(description_file=".dv/description.txt")
        with (box.root / ".dv.toml").open("a") as stream:
            stream.write('allowed_prose_lines = ["' + line + '"]\n')
        box.commit()
        self.assertTrue(self.findings(box, "prose exemptions"))
        self.assertFalse(self.findings(box, "authorship"))

    def test_filler_accumulates_across_prose(self):
        box = self.box()
        box.write(".dv/body.txt", "A comprehensive robust seamless meticulous change.")
        box.update(description_file=".dv/body.txt")
        self.assertEqual(self.findings(box, "prose filler")[0]["outcome"], "fail")
        box.write(".dv/body.txt", "A robust change.")
        self.assertEqual(self.findings(box, "prose filler")[0]["outcome"], "warn")
        self.assertTrue(hygiene.prose_findings("text", "a—b—c—d")[1])

    def test_debug_and_focused_tests(self):
        for statement in ("console.log('x');", "console.debug('x');", "debugger;"):
            box = self.box(new={"src/value.ts": statement + "\nfixed\n"})
            self.assertTrue(self.findings(box, "debug output"), statement)
        box = self.box(new={"tests/value.test.ts": "console.log('ok');\n"})
        self.assertFalse(self.findings(box, "debug output"))
        for marker in ("it.only", "test.only", "describe.only", "fit", "fdescribe"):
            box = self.box(
                new={"tests/value.test.ts": f"{marker}('value', () => {{ expect(1).toBe(1); }});\n"}
            )
            self.assertTrue(self.findings(box, "focused test"), marker)

    def test_each_weak_block_is_independently_checked(self):
        text = "it('good', () => { expect(value).toEqual(2); });\nit('weak', () => { run(); });\n"
        self.assertEqual(len(hygiene.weak_tests("a.test.ts", text, {1, 2})), 1)
        for text in (
            "it('weak', () => { expect(x).toBeDefined(); });",
            "it('weak', () => { expect(x).toBeTruthy(); });",
            "it('weak', () => { expect(x).not.toBeNull(); });",
            "def test_x():\n    assert True\n",
        ):
            self.assertTrue(
                hygiene.weak_tests(
                    "test_a.py" if text.startswith("def") else "a.test.ts", text, {1, 2}
                ),
                text,
            )
        self.assertFalse(
            hygiene.weak_tests("a.test.ts", "it('good', () => { expect(x).toEqual([]); });", {1})
        )

    def test_weak_added_assertion_does_not_reclassify_an_existing_test(self):
        text = "def test_x():\n    assert x == 1\n    assert x\n"
        self.assertFalse(hygiene.weak_tests("tests/test_a.py", text, {3}))

    def test_snapshot_and_generated_tests_are_excluded(self):
        box = self.box(
            new={
                "tests/generated/x.test.ts": "test('x', () => {});\n" * 800,
                "tests/__snapshots__/x.snap": "test('x', () => {});\n",
            }
        )
        output = hygiene.run(box.item)
        self.assertTrue(output["ok"], output)
        self.assertEqual(output["stats"]["generated_lines"], 800)
        self.assertEqual(output["stats"]["snapshot_lines"], 1)

    def test_generated_path_patterns(self):
        for name in ("src/generated/x.ts", "src/__generated__/x.ts", "x.generated.ts", "x.gen.rs"):
            self.assertTrue(hygiene.is_generated(name, {}), name)
        self.assertFalse(hygiene.is_generated("src/generator.ts", {}))
        self.assertTrue(hygiene.is_generated("api/types.ts", {"generated_paths": ["api/*.ts"]}))

    def test_junk_still_fails_when_generated(self):
        box = self.box(new={"dist/generated/a.ts": "// generated\n", ".env.local": "EXAMPLE=1\n"})
        self.assertEqual(len(self.findings(box, "junk path")), 2)

    def test_lockfiles_require_reason_and_have_separate_size(self):
        box = self.box(new={"Cargo.lock": "dependency\n" * 1000})
        output = hygiene.run(box.item)
        self.assertTrue(self.findings(box, "lockfile"))
        self.assertEqual(output["stats"]["lockfile_lines"], 1000)
        self.assertLess(output["stats"]["src_lines"], 10)
        box.update(
            exceptions={"lockfile_reason": "Updates the parser dependency required by this fix"}
        )
        self.assertFalse(self.findings(box, "lockfile"))

    def test_missing_regression_and_waiver(self):
        box = self.box(
            new={
                "tests/test_value.py": (
                    "import unittest\n\nclass ValueTests(unittest.TestCase):\n    def tes"
                    "t_initial(self):\n        self.assertEqual(1, 1)\n"
                )
            }
        )
        self.assertTrue(self.findings(box, "regression test"))
        box.update(exceptions={"no_test_reason": "Only the external format documentation changed"})
        self.assertFalse(self.findings(box, "regression test"))

    def test_source_cap_ignores_large_tests_and_generated(self):
        box = self.box(
            new={"tests/fixture.data": "entry\n" * 1300, "src/x.generated.ts": "value\n" * 1000}
        )
        output = hygiene.run(box.item)
        self.assertTrue(output["ok"], output)
        self.assertGreater(output["stats"]["test_lines"], 1200)
        self.assertEqual(self.findings(box, "test size")[0]["outcome"], "warn")
        box.write("src/large.ts", "value\n" * 450)
        box.commit()
        self.assertEqual(self.findings(box, "source size")[0]["outcome"], "fail")
        box.update(kind="large")
        self.assertEqual(self.findings(box, "source size")[0]["outcome"], "warn")

    def test_deleted_and_binary_paths_are_counted(self):
        box = self.box(
            old={"src/old.ts": "a\n" * 40, "src/image.bin": b"\0before"},
            new={"src/old.ts": None, "src/image.bin": b"\0after"},
        )
        output = hygiene.run(box.item)
        self.assertEqual(output["stats"]["src_lines"], 42)
        self.assertEqual(output["stats"]["binary_files"], 1)
        self.assertIn("src/old.ts", [file["path"] for file in output["files"]])

    def test_renames_and_unusual_paths_remain_unambiguous(self):
        box = self.box(
            old={"src/old.ts": "x\n"},
            new={"src/old.ts": None, "src/new file\tname.ts": "x\n", "src/line\nbreak.ts": "y\n"},
        )
        output = hygiene.run(box.item)
        self.assertIn("src/new file\tname.ts", [file["path"] for file in output["files"]])
        self.assertEqual(output["stats"]["src_lines"], 5)

    def test_rust_trailing_modules_and_bare_functions(self):
        for prefix in ("#[cfg(test)]\nmod tests {\n", "#[test]\nfn test_value() {\n"):
            body = "pub fn value() -> u8 { 1 }\n" + prefix + "    assert_eq!(1, 1);\n" * 500 + "}\n"
            box = self.box(new={"src/value.rs": body})
            output = hygiene.run(box.item)
            self.assertTrue(output["ok"], output)
            self.assertGreater(output["stats"]["inline_rust_test_lines"], 500)
            self.assertLess(output["stats"]["src_lines"], 10)

    def test_rust_deletions_use_old_file_boundary(self):
        old = (
            "pub fn value() {}\n#[test]\nfn test_value() {\n"
            + "    assert_eq!(1, 1);\n" * 100
            + "}\n"
        )
        box = self.box(old={"src/old.rs": old}, new={"src/old.rs": None})
        output = hygiene.run(box.item)
        self.assertEqual(output["stats"]["inline_rust_test_lines"], 103)
        self.assertEqual(output["stats"]["src_lines"], 3)

    def test_rust_production_after_test_is_not_hidden(self):
        body = "#[test]\nfn test_x() { assert_eq!(1, 1); }\npub fn production() {}\n"
        start, ambiguous = hygiene.rust_test_start(body)
        self.assertIsNone(start)
        self.assertTrue(ambiguous)
        box = self.box(new={"src/a.rs": body})
        self.assertTrue(self.findings(box, "Rust layout"))
        self.assertEqual(hygiene.run(box.item)["stats"]["inline_rust_test_lines"], 0)

    def test_rust_braces_in_strings_do_not_truncate_tests(self):
        text = 'pub fn x() {}\n#[test]\nfn test_x() { let x = "}"; assert_eq!(x, "}"); }\n'
        self.assertEqual(hygiene.rust_test_start(text), (2, False))

    def test_whitespace_exit_status_not_diagnostic_controls_failure(self):
        box = self.box()
        item = box.item
        real = item.repo.run

        def run(*args, **kwargs):
            if args[:2] == ("diff", "--check"):
                return subprocess.CompletedProcess(args, 2, b"", b"")
            return real(*args, **kwargs)

        with patch.object(item.repo, "run", side_effect=run):
            output = hygiene.inspect(item)
        self.assertFalse(output["ok"])
        self.assertIn("exit=2", str(output))

    def test_todos_and_commit_noise(self):
        box = self.box(new={"src/unfinished.ts": "// TODO remove workaround\n"})
        self.assertTrue(self.findings(box, "unfinished work"))
        for index in range(3):
            box.write("src/noise.ts", f"value = {index};\n")
            box.commit()
        self.assertTrue(self.findings(box, "commit noise"))

    def test_stacked_base_uses_lower_branch(self):
        from support import git

        box = self.box()
        git(box.root, "branch", "lower")
        box.write("src/upper.ts", "value\n")
        box.write("tests/upper.fixture", "expected\n")
        box.commit()
        box.update(base_ref="lower")
        output = hygiene.run(box.item)
        self.assertEqual(output["stats"]["files"], 2)
        self.assertEqual(output["stats"]["src_lines"], 1)
